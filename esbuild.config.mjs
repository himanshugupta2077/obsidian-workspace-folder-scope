import esbuild from "esbuild";
import process from "process";
import { copyFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { builtinModules } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/himanshugupta2077/obsidian-workspace-folder-scope
*/
`;

const prod = process.argv[2] === "production";

// Optional: VAULTS="/path/to/vault1:/path/to/vault2" installs each build into those vaults.
const vaults = (process.env.VAULTS ?? "").split(":").filter(Boolean);
const install = {
	name: "install",
	setup: (build) =>
		build.onEnd((result) => {
			if (result.errors.length) return;
			for (const vault of vaults) {
				const dir = join(vault, ".obsidian", "plugins", "workspace-folder-scope");
				mkdirSync(dir, { recursive: true });
				for (const f of ["main.js", "manifest.json", "styles.css"]) copyFileSync(f, join(dir, f));
				console.log(`installed → ${dir}`);
			}
		}),
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
		...builtinModules.map((m) => `node:${m}`),
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [install],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
